"""
verify_provenance.py - Official EconData extract loader + verification.

The hackathon requires the USDZAR series EXCX135 as distributed by EconData.
This script:
  1. parses the official EconData CSV export (data/raw/econdata_excx135.csv),
  2. writes a clean date,value file the pipeline can consume, and
  3. verifies it is numerically identical to the SARB Web API series
     (data/raw/usdzar.csv, code EXCX135D) that fetch_data.py downloads.

How the extract was produced (reproducible by any judge with a free account):
  econdata.co.za -> Data query -> South African Reserve Bank -> Rates
    -> Data set "Market Rates" -> search "EXCX135"
    -> tick "Rand per US Dollar - EXCX135.B.A" -> Submit
    -> Export -> "Comma separated values"

Equivalent econdatar (R) call, as generated by the EconData Export dialog:

    read_dataset(
      id         = "MARKET_RATES",
      version    = "1.0.0",
      series_key = "EXCX135.B.A",
      release    = "ZARIBOR & ZARONIA")

Citation: SARB. MARKET_RATES. Version 1.0.0. Pretoria: SARB [producer].
          Johannesburg: EconData [distributor], 2026.
"""
import json
from pathlib import Path

import pandas as pd

BASE = Path(__file__).resolve().parents[1]
RAW = BASE / "data" / "raw"
SRC = RAW / "econdata_excx135.csv"
CLEAN = RAW / "econdata_excx135_clean.csv"
PROVENANCE = BASE / "data" / "processed" / "provenance.json"


def load_econdata() -> pd.DataFrame:
    """Parse the EconData export: a metadata block, then date,value rows."""
    rows, meta = [], {}
    with open(SRC, encoding="utf-8-sig") as fh:
        for line in fh:
            parts = line.rstrip("\n").split(",")
            if len(parts) < 2:
                continue
            key, val = parts[0].strip(), parts[1].strip()
            if key[:4].isdigit() and "-" in key:          # a data row
                if val:
                    rows.append((key, float(val)))
            elif not rows:                                 # header metadata
                meta[key] = val
    df = pd.DataFrame(rows, columns=["date", "econdata"])
    df["date"] = pd.to_datetime(df["date"])
    return df.sort_values("date").reset_index(drop=True), meta


def main() -> None:
    ecd, meta = load_econdata()
    ecd.rename(columns={"econdata": "value"}).to_csv(CLEAN, index=False)

    sarb = pd.read_csv(RAW / "usdzar.csv", parse_dates=["date"]).rename(
        columns={"value": "sarb_webapi"})
    m = ecd.merge(sarb, on="date")
    diff = (m["econdata"] - m["sarb_webapi"]).abs()

    print("EconData export")
    for k in ["Label", "Frequency", "Start", "End", "Source ID"]:
        print(f"  {k:<12}: {meta.get(k, '')}")
    print(f"  observations: {len(ecd)}  "
          f"({ecd.date.min():%Y-%m-%d} to {ecd.date.max():%Y-%m-%d})")
    print("\nVerification vs SARB Web API series EXCX135D")
    print(f"  overlapping observations : {len(m)}")
    print(f"  max |difference|         : {diff.max():.6f}")
    print(f"  mismatching observations : {int((diff > 1e-9).sum())}")
    print(f"  IDENTICAL                : {bool((diff <= 1e-9).all())}")

    # the window that actually matters for the competition
    w = m[(m.date >= "2020-12-01") & (m.date <= "2026-02-01")]
    d2 = (w["econdata"] - w["sarb_webapi"]).abs()
    print(f"\n  2021-2025 forecast window: {len(w)} obs, "
          f"max |diff| = {d2.max():.6f}, identical = {bool((d2 <= 1e-9).all())}")

    PROVENANCE.write_text(json.dumps(dict(
        econdata_observations=len(ecd), econdata_first_date=f"{ecd.date.min():%Y-%m-%d}",
        overlapping_observations=len(m), max_abs_difference=float(diff.max()),
        mismatching_observations=int((diff > 1e-9).sum()),
        forecast_window_observations=len(w),
        forecast_window_max_abs_difference=float(d2.max())), indent=2))


if __name__ == "__main__":
    main()
